export const visualByKey = (key) => VISUALS.find((v) => v.key === key) || null;
/** infographic that explains this question (for the link under the explanation), if any */
export const visualForQuestion = (id) => VISUALS.find((v) => allRefs(v).includes(id)) || null;
export const visualForUnit = (unitKey) => VISUALS.filter((v) => v.units.includes(unitKey));
export function allRefs(v) {
  const ids = new Set();
  for (const f of v.facts || []) f.refs.forEach((r) => ids.add(r));
  for (const s of v.systems || []) s.refs.forEach((r) => ids.add(r));
  return [...ids];
}
